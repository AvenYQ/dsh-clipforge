/**
 * 站点 Cookie 采集：用本机 ego 浏览器打开站点，通过 CDP 导出 cookie 并写成
 * yt-dlp 可用的 Netscape 格式。抖音这类站点要求“新鲜 cookie”，匿名访问即可满足。
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { MARKER, runBrowser } from './browser.js';

export const COOKIE_DIR = path.join(os.homedir(), '.dsh', 'workbench', 'cookies');

export function cookiePathFor(host) {
  return path.join(COOKIE_DIR, `${host.replace(/^www\./, '')}.txt`);
}

function netscape(cookies, host) {
  const rows = cookies
    .filter((cookie) => cookie.domain && (cookie.domain.includes(host) || host.includes(cookie.domain.replace(/^\./, ''))))
    .map((cookie) => {
      const domain = `${cookie.httpOnly ? '#HttpOnly_' : ''}${cookie.domain}`;
      const includeSub = cookie.domain.startsWith('.') ? 'TRUE' : 'FALSE';
      const secure = cookie.secure ? 'TRUE' : 'FALSE';
      const expires = Math.max(0, Math.floor(cookie.expires || 0));
      return [domain, includeSub, cookie.path || '/', secure, expires, cookie.name, cookie.value].join('\t');
    });
  return `# Netscape HTTP Cookie File\n# generated by dsh-workbench\n${rows.join('\n')}\n`;
}

export async function captureCookies(host, { force = false } = {}) {
  const target = cookiePathFor(host);
  if (!force) {
    try {
      const stat = await fs.stat(target);
      /* 半小时内的 cookie 视为新鲜 */
      if (Date.now() - stat.mtimeMs < 30 * 60 * 1000) return target;
    } catch { /* 不存在则继续采集 */ }
  }

  const script = `
const space = await taskSpaces.useOrCreate('workbench');
await page.goto(${JSON.stringify(`https://${host}/`)}, { waitUntil: 'domcontentloaded' });
await new Promise((resolve) => setTimeout(resolve, 2500));
const all = await cdp('Network.getAllCookies', {});
console.log(${JSON.stringify(MARKER)} + JSON.stringify({ cookies: (all && all.cookies) || [] }));
`;
  const data = await runBrowser(script, { timeout: 120_000 });
  if (!data?.cookies?.length) throw new Error(`没有从 ${host} 拿到 cookie`);

  await fs.mkdir(COOKIE_DIR, { recursive: true });
  await fs.writeFile(target, netscape(data.cookies, host), 'utf8');
  return target;
}
